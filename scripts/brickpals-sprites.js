import { readFileSync, writeFileSync } from "fs";
import { join } from "path";

const SHARED_DIR = join(".code", "brick-pals", "shared");
const SPRITES_DIR = join(SHARED_DIR, "sprites");
const OUTPUT = join(
  ".vitepress",
  "theme",
  "components",
  "misc",
  "brickpals",
  "sprites.ts"
);

// Bo, the pal the store screenshots show.
const SPECIES = 1;
const SPECIES_COUNT = 5;

const PAL_FRAMES = [
  "baby",
  "baby-bob",
  "baby-closed",
  "baby-happy",
  "baby-happy-bob",
  "baby-happy-stretch",
];
// Every pal hatches into a silhouette, so the page does not spoil what the
// pals look like (the store images show only Bo).
const HATCH_FRAMES = ["egg", "hatching"];
const HATCH_SILHOUETTES = [
  "baby",
  "baby-bob",
  "child",
  "child-bob",
  "teen",
  "teen-bob",
  "adult",
  "adult-bob",
];
const FOOD = ["apple-1", "apple-2", "apple-3"];
const FX = ["heart", "note", "zzz", "steps", "bolt", "drop"];
const DECOR_FOOD = ["apple-1", "bowl-1", "cookie-1", "grapes-1", "milk-1"];

const readSprite = (...path) =>
  readFileSync(join(SPRITES_DIR, ...path) + ".txt", "utf-8")
    .split("\n")
    .filter((row) => row.length > 0);

const NEIGHBORS = [
  [1, 0],
  [-1, 0],
  [0, 1],
  [0, -1],
];

/**
 * Fills the sprite's outline, so only its shape is left. Every empty pixel
 * that cannot be reached from the edge is inside the pal.
 *
 * Some outlines have one-pixel openings (such as `##.######.##` at the
 * feet), which would let the fill reach inside and leave the art showing.
 * So the outline is first grown by one pixel to close those openings, the
 * outside is filled, and the shape is then shrunk back by one pixel.
 */
const silhouette = (rows) => {
  const height = rows.length;
  const width = rows[0].length;
  const lit = (x, y) =>
    x >= 0 && y >= 0 && x < width && y < height && rows[y][x] === "#";
  const grown = (x, y) =>
    lit(x, y) || NEIGHBORS.some(([dx, dy]) => lit(x + dx, y + dy));

  const outside = rows.map((row) => [...row].map(() => false));
  const queue = [];
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const isEdge = x === 0 || y === 0 || x === width - 1 || y === height - 1;
      if (isEdge) queue.push([x, y]);
    }
  }
  while (queue.length > 0) {
    const [x, y] = queue.pop();
    if (x < 0 || y < 0 || x >= width || y >= height) continue;
    if (outside[y][x] || grown(x, y)) continue;
    outside[y][x] = true;
    queue.push(...NEIGHBORS.map(([dx, dy]) => [x + dx, y + dy]));
  }

  // Shrinking back: a pixel stays filled only if no neighbor is outside.
  const isOutside = (x, y) =>
    x < 0 || y < 0 || x >= width || y >= height || outside[y][x];
  const filled = (x, y) =>
    lit(x, y) ||
    (!isOutside(x, y) &&
      NEIGHBORS.every(([dx, dy]) => !isOutside(x + dx, y + dy)));

  return rows.map((row, y) =>
    [...row].map((_, x) => (filled(x, y) ? "#" : ".")).join("")
  );
};

const toKey = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());

const entries = (names, read) =>
  Object.fromEntries(names.map((name) => [toKey(name), read(name)]));

function main() {
  const data = {
    pal: entries(PAL_FRAMES, (name) => readSprite("pals", `${SPECIES}`, name)),
    eggs: Array.from({ length: SPECIES_COUNT }, (_, i) => ({
      ...entries(HATCH_FRAMES, (name) => readSprite("pals", `${i + 1}`, name)),
      ...entries(HATCH_SILHOUETTES, (name) =>
        silhouette(readSprite("pals", `${i + 1}`, name))
      ),
    })),
    food: FOOD.map((name) => readSprite("food", name)),
    decorFood: entries(DECOR_FOOD, (name) => readSprite("food", name)),
    fx: entries(FX, (name) => readSprite("fx", name)),
    font: JSON.parse(readFileSync(join(SHARED_DIR, "font-3x5.json"), "utf-8")),
    palettes: JSON.parse(
      readFileSync(join(SHARED_DIR, "palettes.json"), "utf-8")
    ),
    shells: JSON.parse(readFileSync(join(SHARED_DIR, "shells.json"), "utf-8")),
  };

  const source = [
    "// Generated by scripts/brickpals-sprites.js from the Brick Pals app. Do not edit.",
    "",
    ...Object.entries(data).map(
      ([name, value]) =>
        `export const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`
    ),
  ].join("\n");

  writeFileSync(OUTPUT, source);
}

main();
